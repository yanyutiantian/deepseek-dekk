    private static String join(String[] lines) {
        StringBuilder builder = new StringBuilder();
        for (int i = 0; i < lines.length; i++) {
            builder.append(lines[i]);
            if (i + 1 < lines.length) {
                builder.append('\n');
            }
        }
        return builder.toString();
    }

